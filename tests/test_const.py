from gatt_link_ble.const import (
    BATTERY_LEVEL_CHAR_UUID,
    BATTERY_SERVICE_UUID,
    DEVICE_INFORMATION_SERVICE_UUID,
    ENVIRONMENTAL_SENSING_SERVICE_UUID,
    THINGY_ENVIRONMENT_SERVICE_UUID,
    THINGY_GAS_CHAR_UUID,
)


def test_standard_bluetooth_uuids_use_the_bluetooth_base_uuid() -> None:
    assert BATTERY_SERVICE_UUID == "0000180f-0000-1000-8000-00805f9b34fb"
    assert BATTERY_LEVEL_CHAR_UUID == "00002a19-0000-1000-8000-00805f9b34fb"
    assert DEVICE_INFORMATION_SERVICE_UUID == "0000180a-0000-1000-8000-00805f9b34fb"
    assert ENVIRONMENTAL_SENSING_SERVICE_UUID == (
        "0000181a-0000-1000-8000-00805f9b34fb"
    )


def test_thingy_environment_uuids() -> None:
    assert THINGY_ENVIRONMENT_SERVICE_UUID == "ef680200-9b35-4933-9b10-52ffa9740042"
    assert THINGY_GAS_CHAR_UUID == "ef680204-9b35-4933-9b10-52ffa9740042"
